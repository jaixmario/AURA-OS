# Scale 8x8 to 8x16 (each row doubled)
font8x16 = []
for code in range(32, 128):
    ch = chr(code)
    rows8 = font8x8_basic.get(ch, [0]*8)
    rows16 = []
    for r in rows8:
        rows16.append(r)
        rows16.append(r)
    font8x16.append(rows16)

with open(out_path, 'w') as f:
    f.write('#include "font.h"\n\n')
    f.write('const unsigned char font8x16[96][16] = {\n')
    for idx, rows in enumerate(font8x16):
        ch = chr(32 + idx)
        ch_disp = ch if ch != '\\' and ch != "'" else 'slash'
        f.write(f'    // ASCII {32+idx} \'{ch_disp}\'\n    {{ ')
        f.write(', '.join(f'0x{r:02X}' for r in rows))
        f.write(' },\n')
    f.write('};\n')

